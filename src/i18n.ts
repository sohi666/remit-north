export const STRINGS: Record<Lang, Strings> = { en, fr };

export function deviceLang(): Lang {
  try {
    return getLocales()[0]?.languageCode === 'fr' ? 'fr' : 'en';
  } catch {
    return 'en';
  }
}

export function money(n: number, lang: Lang, cents = true) {
  const v = Number.isFinite(n) ? n : 0;
  const s = new Intl.NumberFormat(lang === 'fr' ? 'fr-CA' : 'en-CA', {
    minimumFractionDigits: cents ? 2 : 0,
    maximumFractionDigits: cents ? 2 : 0,
  }).format(v);
  return lang === 'fr' ? `${s} $` : `$${s}`.replace('$-', '-$');
}

export function pct(n: number, lang: Lang, digits = 1) {
  const s = new Intl.NumberFormat(lang === 'fr' ? 'fr-CA' : 'en-CA', { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n * 100);
  return lang === 'fr' ? `${s} %` : `${s}%`;
}
